// Turns data/careers/industries.json (careers typical of each industry) into
// one idempotent SQL migration that fills industry_occupations.
//
//   node scripts/build-industry-careers-sql.mjs <input.json> <output.sql>
//
// Careers are matched by exact title; a title with no career is skipped, and
// nothing is created or deleted. "everywhere" careers are stored once per
// industry with common = true, after the industry's own.
import { readFile, writeFile } from 'node:fs/promises';

const [input, output] = process.argv.slice(2);
if (!input || !output) {
  console.error('usage: node scripts/build-industry-careers-sql.mjs <input.json> <output.sql>');
  process.exit(1);
}
const q = (text) => `'${String(text).replace(/'/g, "''")}'`;
const { everywhere, industries } = JSON.parse(await readFile(input, 'utf8'));

const rows = [];
for (const { industry, careers } of industries) {
  careers.forEach((title, i) => rows.push(`  (${q(industry)}, ${q(title)}, ${i + 1}, false)`));
  everywhere
    .filter((title) => !careers.includes(title))
    .forEach((title, i) => rows.push(`  (${q(industry)}, ${q(title)}, ${careers.length + i + 1}, true)`));
}

const lines = [
  `-- Careers typical of each industry, loaded from ${input}.`,
  '-- Generated by scripts/build-industry-careers-sql.mjs. Edit the JSON and regenerate.',
  '-- Idempotent: creates the table if missing, matches careers by exact title,',
  '-- skips titles that do not exist, and never deletes.',
  '',
  'CREATE TABLE IF NOT EXISTS "industry_occupations" (',
  '  "industry" text NOT NULL,',
  '  "occupation_id" uuid NOT NULL REFERENCES "occupations"("id") ON DELETE CASCADE,',
  '  -- Order within the industry: its own careers first, then those found everywhere.',
  '  "rank" integer NOT NULL,',
  '  -- True for careers found in plants of every industry (maintenance, controls, quality).',
  '  "common" boolean NOT NULL DEFAULT false,',
  '  PRIMARY KEY ("industry", "occupation_id")',
  ');',
  'CREATE INDEX IF NOT EXISTS "industry_occupations_occupation_idx" ON "industry_occupations" ("occupation_id");',
  '-- The industry of a factory is looked up by this column on every panel that lists careers.',
  'CREATE INDEX IF NOT EXISTS "factories_primary_naics_description_idx" ON "factories" ("primary_naics_description");',
  '',
  'INSERT INTO "industry_occupations" ("industry", "occupation_id", "rank", "common")',
  'SELECT v.industry, o.id, v.rank, v.common',
  'FROM (VALUES',
  rows.join(',\n'),
  ') AS v(industry, title, rank, common)',
  'INNER JOIN occupations o ON o.title = v.title',
  'ON CONFLICT ("industry", "occupation_id") DO UPDATE SET "rank" = EXCLUDED."rank", "common" = EXCLUDED."common";',
  '',
];
await writeFile(output, lines.join('\n'));
console.log(`${output}: ${rows.length} rows across ${industries.length} industries`);
