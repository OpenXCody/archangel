// Turns data/paths/*.json into one idempotent SQL migration that loads career
// paths: it creates any missing skills, links each career to its skills with a
// stage, and marks those careers' paths as drafts awaiting review.
//
//   node scripts/build-paths-sql.mjs <input.json> <output.sql>
//
// The SQL only touches careers that exist (matched by exact title), never
// deletes anything, and never overwrites a path a person has approved.
import { readFile, writeFile } from 'node:fs/promises';

const [input, output] = process.argv.slice(2);
if (!input || !output) {
  console.error('usage: node scripts/build-paths-sql.mjs <input.json> <output.sql>');
  process.exit(1);
}

const q = (text) => `'${String(text).replace(/'/g, "''")}'`;
const { careers } = JSON.parse(await readFile(input, 'utf8'));

const skillNames = new Set();
const links = []; // [careerTitle, skillName, stage]
for (const career of careers) {
  const seen = new Set();
  for (const stage of ['1', '2', '3']) {
    for (const name of career.stages[stage] ?? []) {
      if (seen.has(name)) throw new Error(`${career.title}: "${name}" is listed twice`);
      seen.add(name);
      skillNames.add(name);
      links.push([career.title, name, Number(stage)]);
    }
  }
}

const lines = [
  `-- Career paths loaded from ${input}.`,
  '-- Generated by scripts/build-paths-sql.mjs. Do not edit by hand; edit the JSON and regenerate.',
  '-- Idempotent. Creates missing skills, links careers to skills with a stage, and marks',
  "-- those paths 'draft'. A path already marked 'approved' is left exactly as it is.",
  '',
  "ALTER TABLE \"occupations\" ADD COLUMN IF NOT EXISTS \"path_status\" text;",
  '',
  'INSERT INTO skills (name) VALUES',
  [...skillNames].sort().map((n) => `  (${q(n)})`).join(',\n'),
  'ON CONFLICT (name) DO NOTHING;',
  '',
  'INSERT INTO occupation_skills (occupation_id, skill_id, stage)',
  'SELECT o.id, s.id, v.stage',
  'FROM (VALUES',
  links.map(([c, s, st]) => `  (${q(c)}, ${q(s)}, ${st}::smallint)`).join(',\n'),
  ') AS v(career, skill, stage)',
  'JOIN occupations o ON o.title = v.career',
  'JOIN skills s ON s.name = v.skill',
  "WHERE o.path_status IS DISTINCT FROM 'approved'",
  'ON CONFLICT (occupation_id, skill_id) DO UPDATE SET stage = EXCLUDED.stage;',
  '',
  "UPDATE occupations SET path_status = 'draft'",
  `WHERE path_status IS NULL AND title IN (${careers.map((c) => q(c.title)).join(', ')});`,
  '',
];
await writeFile(output, lines.join('\n'));
console.log(`${output}: ${careers.length} careers, ${skillNames.size} skills, ${links.length} links`);
