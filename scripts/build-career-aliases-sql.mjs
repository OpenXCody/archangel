// Turns data/careers/aliases.json (the everyday names careers go by) into one
// idempotent SQL migration that adds them to occupation_aliases.
//
//   node scripts/build-career-aliases-sql.mjs <input.json> <output.sql>
//
// Careers are matched by exact title; a title with no career is skipped. A
// name is left out when it is already an alias, or when a career has it as
// its own title (in any letter case). Nothing is changed or deleted.
import { readFile, writeFile } from 'node:fs/promises';

const [input, output] = process.argv.slice(2);
if (!input || !output) {
  console.error('usage: node scripts/build-career-aliases-sql.mjs <input.json> <output.sql>');
  process.exit(1);
}
const q = (text) => `'${String(text).replace(/'/g, "''")}'`;
const { careers } = JSON.parse(await readFile(input, 'utf8'));

// A name points to one career: the same name twice is a mistake in the list.
const seen = new Map();
const rows = [];
for (const { title, aliases } of careers) {
  for (const alias of aliases) {
    const key = alias.trim().toLowerCase();
    if (seen.has(key)) {
      console.error(`"${alias}" is listed for both "${seen.get(key)}" and "${title}".`);
      process.exit(1);
    }
    seen.set(key, title);
    rows.push(`  (${q(alias.trim())}, ${q(title)})`);
  }
}

const lines = [
  `-- Everyday names for careers, loaded from ${input}.`,
  '-- Generated by scripts/build-career-aliases-sql.mjs. Edit the JSON and regenerate.',
  '-- Idempotent: matches careers by exact title, skips titles that do not exist,',
  '-- skips a name that is already an alias or is some career\'s own title, and never deletes.',
  '',
  'INSERT INTO "occupation_aliases" ("alias_text", "canonical_occupation_id")',
  'SELECT v.alias, o.id',
  'FROM (VALUES',
  rows.join(',\n'),
  ') AS v(alias, title)',
  'INNER JOIN occupations o ON o.title = v.title',
  'WHERE NOT EXISTS (SELECT 1 FROM occupations t WHERE lower(t.title) = lower(v.alias))',
  '  AND NOT EXISTS (SELECT 1 FROM occupation_aliases a WHERE lower(a.alias_text) = lower(v.alias))',
  'ON CONFLICT ("alias_text") DO NOTHING;',
  '',
];
await writeFile(output, lines.join('\n'));
console.log(`${output}: ${rows.length} names for ${careers.length} careers`);
