// Turns a cleanup list (data/cleanup/*.json) into one idempotent SQL migration.
//
//   node scripts/build-cleanup-sql.mjs <input.json> <output.sql>
//
// The list names rows by their exact stored name or title. Everything the
// migration does is a no-op once it has been done: a merge whose source row is
// gone, a rename whose source is gone, a deletion of something already deleted.
//
// A merge keeps one row and moves everything that pointed at the others to it
// (careers: skills, goals, jobs, industries; skills: careers, jobs, people;
// companies: factories, members, jobs, invites), records the old name as an
// alias, then deletes the others.
import { readFile, writeFile } from 'node:fs/promises';

const [input, output] = process.argv.slice(2);
if (!input || !output) {
  console.error('usage: node scripts/build-cleanup-sql.mjs <input.json> <output.sql>');
  process.exit(1);
}
const q = (text) => `'${String(text).replace(/'/g, "''")}'`;
const list = (items) => items.map(q).join(', ');
const data = JSON.parse(await readFile(input, 'utf8'));

const out = [];
const say = (...lines) => out.push(...lines);

say(
  `-- Data cleanup generated from ${input} by scripts/build-cleanup-sql.mjs.`,
  '-- Edit the JSON and regenerate; do not edit this file by hand.',
  '-- Idempotent: each step does nothing once its rows are already as it leaves them.',
  '',
  '-- Helpers live in pg_temp: they exist for this session only.',
  `CREATE FUNCTION pg_temp.merge_career(keep_title text, merged_title text) RETURNS void AS $fn$
DECLARE k uuid; m uuid;
BEGIN
  SELECT id INTO k FROM occupations WHERE title = keep_title;
  SELECT id INTO m FROM occupations WHERE title = merged_title;
  IF m IS NULL OR k IS NULL OR k = m THEN RETURN; END IF;
  UPDATE occupation_skills x SET occupation_id = k WHERE occupation_id = m
    AND NOT EXISTS (SELECT 1 FROM occupation_skills y WHERE y.occupation_id = k AND y.skill_id = x.skill_id);
  UPDATE user_goals x SET occupation_id = k WHERE occupation_id = m
    AND NOT EXISTS (SELECT 1 FROM user_goals y WHERE y.occupation_id = k AND y.user_id = x.user_id);
  UPDATE industry_occupations x SET occupation_id = k WHERE occupation_id = m
    AND NOT EXISTS (SELECT 1 FROM industry_occupations y WHERE y.occupation_id = k AND y.industry = x.industry);
  UPDATE factory_occupations x SET occupation_id = k WHERE occupation_id = m
    AND NOT EXISTS (SELECT 1 FROM factory_occupations y WHERE y.occupation_id = k AND y.factory_id = x.factory_id);
  UPDATE jobs SET occupation_id = k WHERE occupation_id = m;
  UPDATE occupation_aliases SET canonical_occupation_id = k WHERE canonical_occupation_id = m;
  INSERT INTO occupation_aliases (alias_text, canonical_occupation_id) VALUES (merged_title, k) ON CONFLICT (alias_text) DO NOTHING;
  UPDATE occupations o SET
    path_status = COALESCE(o.path_status, (SELECT path_status FROM occupations WHERE id = m)),
    description = COALESCE(NULLIF(btrim(o.description), ''), (SELECT description FROM occupations WHERE id = m))
  WHERE o.id = k;
  DELETE FROM occupations WHERE id = m;
END $fn$ LANGUAGE plpgsql;`,
  '',
  `CREATE FUNCTION pg_temp.merge_skill(keep_name text, merged_name text) RETURNS void AS $fn$
DECLARE k uuid; m uuid;
BEGIN
  SELECT id INTO k FROM skills WHERE name = keep_name;
  SELECT id INTO m FROM skills WHERE name = merged_name;
  IF m IS NULL OR k IS NULL OR k = m THEN RETURN; END IF;
  UPDATE occupation_skills x SET skill_id = k WHERE skill_id = m
    AND NOT EXISTS (SELECT 1 FROM occupation_skills y WHERE y.skill_id = k AND y.occupation_id = x.occupation_id);
  UPDATE job_skills x SET skill_id = k WHERE skill_id = m
    AND NOT EXISTS (SELECT 1 FROM job_skills y WHERE y.skill_id = k AND y.job_id = x.job_id);
  -- A person who marked both keeps the stronger mark (held over learning).
  UPDATE user_skills y SET status = 'held' FROM user_skills x
    WHERE x.skill_id = m AND y.skill_id = k AND y.user_id = x.user_id AND x.status = 'held';
  UPDATE user_skills x SET skill_id = k WHERE skill_id = m
    AND NOT EXISTS (SELECT 1 FROM user_skills y WHERE y.skill_id = k AND y.user_id = x.user_id);
  UPDATE skills SET parent_skill_id = k WHERE parent_skill_id = m;
  UPDATE skill_aliases SET canonical_skill_id = k WHERE canonical_skill_id = m;
  INSERT INTO skill_aliases (alias_text, canonical_skill_id) VALUES (merged_name, k) ON CONFLICT (alias_text) DO NOTHING;
  UPDATE skills s SET
    category = COALESCE(NULLIF(btrim(s.category), ''), (SELECT category FROM skills WHERE id = m)),
    description = COALESCE(NULLIF(btrim(s.description), ''), (SELECT description FROM skills WHERE id = m))
  WHERE s.id = k;
  DELETE FROM skills WHERE id = m;
END $fn$ LANGUAGE plpgsql;`,
  '',
  `CREATE FUNCTION pg_temp.merge_company(keep_name text, merged_name text) RETURNS void AS $fn$
DECLARE k uuid; o companies%ROWTYPE;
BEGIN
  SELECT id INTO k FROM companies WHERE name = keep_name;
  SELECT * INTO o FROM companies WHERE name = merged_name;
  IF o.id IS NULL OR k IS NULL OR k = o.id THEN RETURN; END IF;
  UPDATE factories SET company_id = k WHERE company_id = o.id;
  UPDATE jobs SET company_id = k WHERE company_id = o.id;
  UPDATE invites SET company_id = k WHERE company_id = o.id;
  UPDATE company_members x SET company_id = k WHERE company_id = o.id
    AND NOT EXISTS (SELECT 1 FROM company_members y WHERE y.company_id = k AND y.user_id = x.user_id);
  -- The slug is unique: the row that is going gives it up before the kept row can take it.
  DELETE FROM companies WHERE id = o.id;
  -- The kept company takes whatever profile it lacks, and remembers the old name.
  UPDATE companies c SET
    domain = COALESCE(c.domain, o.domain),
    description = COALESCE(NULLIF(btrim(c.description), ''), o.description),
    industry = CASE WHEN c.industry IS NULL OR lower(btrim(c.industry)) IN ('', 'manufacturing') THEN COALESCE(o.industry, c.industry) ELSE c.industry END,
    featured = c.featured OR o.featured,
    slug = COALESCE(c.slug, o.slug),
    aliases = (SELECT array_agg(DISTINCT a) FROM unnest(COALESCE(c.aliases, '{}') || COALESCE(o.aliases, '{}') || ARRAY[o.name]) AS a),
    updated_at = now()
  WHERE c.id = k;
END $fn$ LANGUAGE plpgsql;`,
  ''
);

// --- Careers ---------------------------------------------------------------
say('-- Careers ---------------------------------------------------------------', '');
if (data.deleteCareers?.titles?.length) {
  say(`-- ${data.deleteCareers.why}`, `DELETE FROM occupations WHERE title IN (${list(data.deleteCareers.titles)});`, '');
}
for (const { keep, merge } of data.mergeCareers ?? []) {
  for (const merged of merge) say(`SELECT pg_temp.merge_career(${q(keep)}, ${q(merged)});`);
}
say('');
for (const { from, to } of data.renameCareers ?? []) {
  say(
    `UPDATE occupations SET title = ${q(to)} WHERE title = ${q(from)} AND NOT EXISTS (SELECT 1 FROM occupations WHERE title = ${q(to)});`,
    `INSERT INTO occupation_aliases (alias_text, canonical_occupation_id) SELECT ${q(from)}, id FROM occupations WHERE title = ${q(to)} ON CONFLICT (alias_text) DO NOTHING;`
  );
}
say('');

// --- Skills ----------------------------------------------------------------
say('-- Skills ----------------------------------------------------------------', '');
const categories = data.skillCategories;
if (categories) {
  say(`-- ${categories.why}`);
  for (const [from, to] of Object.entries(categories.rename ?? {})) {
    say(`UPDATE skills SET category = ${q(to)} WHERE category = ${q(from)};`);
  }
  for (const [category, names] of Object.entries(categories.assign ?? {})) {
    say(
      `UPDATE skills SET category = ${q(category)} WHERE name IN (${list(names)})`,
      `  AND (category IS NULL OR btrim(category) = '' OR category IN ('Root', 'Category', 'Subcategory', 'Skill'));`
    );
  }
  say('');
}
const nodes = data.deleteSkillTreeNodes;
if (nodes) {
  const levels = list(nodes.categories);
  const unused = `category IN (${levels})
    AND NOT EXISTS (SELECT 1 FROM occupation_skills os WHERE os.skill_id = skills.id)
    AND NOT EXISTS (SELECT 1 FROM job_skills js WHERE js.skill_id = skills.id)
    AND NOT EXISTS (SELECT 1 FROM user_skills us WHERE us.skill_id = skills.id)`;
  say(
    `-- ${nodes.why}`,
    `UPDATE skills c SET parent_skill_id = NULL WHERE parent_skill_id IN (SELECT id FROM skills WHERE ${unused});`,
    `DELETE FROM skills WHERE ${unused};`,
    ''
  );
}
for (const { keep, merge } of data.mergeSkills ?? []) {
  for (const merged of merge) say(`SELECT pg_temp.merge_skill(${q(keep)}, ${q(merged)});`);
}
say('');
for (const { from, to } of data.renameSkills ?? []) {
  say(
    `UPDATE skills SET name = ${q(to)} WHERE name = ${q(from)} AND NOT EXISTS (SELECT 1 FROM skills WHERE name = ${q(to)});`,
    `INSERT INTO skill_aliases (alias_text, canonical_skill_id) SELECT ${q(from)}, id FROM skills WHERE name = ${q(to)} ON CONFLICT (alias_text) DO NOTHING;`
  );
}
say('');

// --- Companies -------------------------------------------------------------
say('-- Companies -------------------------------------------------------------', '');
const rename = (from, to) =>
  say(
    `UPDATE companies SET name = ${q(to)}, aliases = (SELECT array_agg(DISTINCT a) FROM unnest(COALESCE(aliases, '{}') || ARRAY[${q(from)}]) AS a), updated_at = now()`,
    `  WHERE name = ${q(from)} AND NOT EXISTS (SELECT 1 FROM companies WHERE name = ${q(to)});`
  );
for (const group of data.mergeCompanies ?? []) {
  for (const merged of group.merge) say(`SELECT pg_temp.merge_company(${q(group.keep)}, ${q(merged)});`);
  if (group.rename) rename(group.keep, group.rename);
}
say('');
for (const { from, to } of data.renameCompanies ?? []) rename(from, to);
say(
  '',
  '-- Names that kept an HTML entity from their source.',
  `UPDATE companies SET name = replace(name, '&amp;', '&'), updated_at = now()`,
  `  WHERE name LIKE '%&amp;%' AND NOT EXISTS (SELECT 1 FROM companies o WHERE o.name = replace(companies.name, '&amp;', '&'));`,
  ''
);

// --- Factories -------------------------------------------------------------
say('-- Factories -------------------------------------------------------------', '');
const moves = data.moveFactories;
if (moves) {
  say(`-- ${moves.why}`);
  for (const target of [...new Set(moves.moves.map((move) => move.toCompany))]) {
    say(`INSERT INTO companies (name) SELECT ${q(target)} WHERE NOT EXISTS (SELECT 1 FROM companies WHERE name = ${q(target)});`);
  }
  for (const { fromCompany, factory, toCompany } of moves.moves) {
    say(
      `UPDATE factories SET company_id = (SELECT id FROM companies WHERE name = ${q(toCompany)}), updated_at = now()`,
      `  WHERE name = ${q(factory)} AND company_id = (SELECT id FROM companies WHERE name = ${q(fromCompany)});`
    );
  }
  say('');
}
for (const profile of data.companyProfiles ?? []) {
  say(
    `UPDATE companies SET domain = COALESCE(domain, ${q(profile.domain)}), featured = ${profile.featured ? 'true' : 'featured'},`,
    `  industry = CASE WHEN industry IS NULL OR lower(btrim(industry)) IN ('', 'manufacturing') THEN ${q(profile.industry)} ELSE industry END,`,
    `  description = COALESCE(NULLIF(btrim(description), ''), ${q(profile.description)}),`,
    `  slug = COALESCE(slug, CASE WHEN NOT EXISTS (SELECT 1 FROM companies o WHERE o.slug = ${q(profile.slug)}) THEN ${q(profile.slug)} END), updated_at = now()`,
    `  WHERE name = ${q(profile.name)};`
  );
}
if (data.companyProfiles?.length) say('');
const gone = data.deleteFactories;
if (gone) {
  say(`-- ${gone.why}`);
  for (const { company, factory, city } of gone.rows) {
    say(
      `DELETE FROM factories WHERE name = ${q(factory)} AND company_id = (SELECT id FROM companies WHERE name = ${q(company)})${city ? ` AND upper(city) = ${q(city.toUpperCase())}` : ''};`
    );
  }
  say('');
}
const rules = data.factoryRules;
if (rules) {
  const metres = Number(rules.duplicateWithinMetres) || 0;
  say(
    '-- Plants with no real place: portable plants and vessels pinned to the middle of a state.',
    `DELETE FROM factories WHERE upper(btrim(city)) IN (${list(rules.placeholderCities)});`,
    '',
    '-- A state name where the city should be says nothing: clear it.',
    `UPDATE factories SET city = NULL WHERE upper(btrim(city)) IN ('FLORIDA', 'CALIFORNIA') AND state IN ('FL', 'CA');`,
    '',
    '-- A registry number left in front of the name ("105123 - MODERN FORGE INDIANA").',
    `UPDATE factories SET name = regexp_replace(name, '^#?[0-9]+ +[-–] *', ''), updated_at = now()`,
    `  WHERE name ~ '^#?[0-9]+ +[-–] *[A-Za-z]';`,
    '',
    `-- The same plant recorded twice: same company, same name once punctuation is`,
    `-- ignored, within ${metres} metres. One is kept (the one that knows its`,
    '-- industry, then its city, then the older row); jobs move to it first.',
    `CREATE FUNCTION pg_temp.remove_duplicate_factories(metres float8) RETURNS integer AS $fn$
DECLARE removed integer := 0; n integer;
BEGIN
  FOR pass IN 1..6 LOOP
    CREATE TEMP TABLE cleanup_f ON COMMIT DROP AS
      SELECT id, company_id, latitude::float8 AS lat, longitude::float8 AS lng, created_at,
             (primary_naics_description IS NOT NULL)::int AS has_industry, (city IS NOT NULL)::int AS has_city,
             btrim(regexp_replace(lower(replace(name, '&', ' and ')), '[^a-z0-9]+', ' ', 'g')) AS k
      FROM factories
      WHERE latitude ~ '^-?[0-9]+([.][0-9]+)?$' AND longitude ~ '^-?[0-9]+([.][0-9]+)?$';
    CREATE INDEX ON cleanup_f (company_id, k);
    -- (worse, better): the same plant twice, close together; "better" knows more or is older.
    CREATE TEMP TABLE cleanup_pairs ON COMMIT DROP AS
      SELECT b.id AS worse, a.id AS better, a.has_industry, a.has_city, a.created_at
      FROM cleanup_f a JOIN cleanup_f b ON a.company_id = b.company_id AND a.k = b.k AND a.id <> b.id
      WHERE ((a.has_industry, a.has_city) > (b.has_industry, b.has_city)
             OR ((a.has_industry, a.has_city) = (b.has_industry, b.has_city) AND (a.created_at, a.id) < (b.created_at, b.id)))
        -- About 111 km per degree of latitude; longitude shrinks with the cosine.
        AND sqrt(power((a.lat - b.lat) * 111320, 2) + power((a.lng - b.lng) * 111320 * cos(radians(a.lat)), 2)) <= metres;
    -- Only rows whose better twin is itself staying this pass, so a job never moves to a row about to go.
    CREATE TEMP TABLE cleanup_go ON COMMIT DROP AS
      SELECT DISTINCT ON (worse) worse AS id, better AS keep_id
      FROM cleanup_pairs p
      WHERE NOT EXISTS (SELECT 1 FROM cleanup_pairs q WHERE q.worse = p.better)
      ORDER BY worse, has_industry DESC, has_city DESC, created_at ASC, better;
    SELECT count(*) INTO n FROM cleanup_go;
    IF n > 0 THEN
      UPDATE jobs SET factory_id = g.keep_id FROM cleanup_go g WHERE jobs.factory_id = g.id;
      DELETE FROM factories WHERE id IN (SELECT id FROM cleanup_go);
      removed := removed + n;
    END IF;
    DROP TABLE cleanup_go; DROP TABLE cleanup_pairs; DROP TABLE cleanup_f;
    EXIT WHEN n = 0;
  END LOOP;
  RETURN removed;
END $fn$ LANGUAGE plpgsql;`,
    `SELECT pg_temp.remove_duplicate_factories(${metres});`,
    ''
  );
}

await writeFile(output, out.join('\n'));
console.log(`${output}: ${out.length} lines`);
