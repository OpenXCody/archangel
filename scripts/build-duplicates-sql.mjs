// Builds the migration that leaves one row for one plant.
//
//   node scripts/build-duplicates-sql.mjs [--out migrations/0051_plant_duplicates.sql]
//   node scripts/build-duplicates-sql.mjs --check          the migration is what this would write
//   node scripts/build-duplicates-sql.mjs --rehearse [--all] --out rehearsal.sql
//
// The migration is three files, in this order:
//   scripts/plant-merge.sql        what stays: plants_apart, plant_keeps, plant_merge
//   scripts/employers-loader.sql   the loader's name rules and its company merge (pg_temp)
//   scripts/plant-duplicates.sql   the cleanup's own rules (pg_temp), then one call that runs it
// It names no id: it finds every outside id more than one live plant carries
// and decides in SQL on the database it meets, writing each decision to
// load_log (load `plant-duplicates`). Run twice, the second run changes nothing.
//
// --rehearse writes SQL to run all at once, on one connection, against a copy
// of production: it does the whole cleanup, returns a summary and the lines
// marked for a look (every line with --all), and undoes everything before it
// returns. The database is as it was, committed or rolled back.
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath, pathToFileURL } from 'node:url';
import path from 'node:path';

const HERE = path.dirname(fileURLToPath(import.meta.url));
export const MIGRATION = path.join(HERE, '..', 'migrations', '0051_plant_duplicates.sql');
export const LOAD = 'plant-duplicates';

/** The SQL: the migration, or a rehearsal of it that undoes itself. */
export async function buildSql({ rehearse = false, everything = false } = {}) {
  const [merge, loader, cleanup] = await Promise.all(
    ['plant-merge.sql', 'employers-loader.sql', 'plant-duplicates.sql'].map((name) => readFile(path.join(HERE, name), 'utf8'))
  );
  const rule = '-- ' + '-'.repeat(75);
  if (rehearse) {
    if (merge.includes('$pd_schema$')) throw new Error('scripts/plant-merge.sql uses the tag the rehearsal quotes it with.');
    return [
      '-- A rehearsal of the plant-duplicates cleanup. Generated by scripts/build-duplicates-sql.mjs: do not edit.',
      '-- Run it all at once on one connection. It changes nothing: the work is undone before it returns.',
      '',
      loader.trimEnd(),
      '',
      cleanup.trimEnd(),
      '',
      `SELECT * FROM pg_temp.pd_rehearse($pd_schema$\n${merge.trimEnd()}\n$pd_schema$, ${everything ? 'true' : 'false'});`,
      '',
    ].join('\n');
  }
  return [
    '-- One row for one plant. Generated by scripts/build-duplicates-sql.mjs from scripts/plant-merge.sql,',
    '-- scripts/employers-loader.sql and scripts/plant-duplicates.sql: do not edit; change those and build again.',
    '--',
    '-- It adds the plant merge the database keeps (plant_merge, plant_keeps, plants_apart), then cleans up:',
    '-- every outside id (the EPA registry id) carried by more than one live plant is decided in SQL, on the',
    '-- database this runs on. Rows that are certainly one plant are merged; the rest are left for a person,',
    '-- listed in Admin Tools. References to plants that no longer exist are removed. Every decision is a line',
    `-- in load_log (load '${LOAD}'; look = true on the ones to read). Safe to run again: a second run`,
    '-- finds nothing to merge and writes nothing.',
    '',
    rule,
    '-- What stays (scripts/plant-merge.sql)',
    rule,
    '',
    merge.trimEnd(),
    '',
    rule,
    "-- The employer loader's functions (scripts/employers-loader.sql): this session only",
    rule,
    '',
    loader.trimEnd(),
    '',
    rule,
    '-- The cleanup (scripts/plant-duplicates.sql): this session only',
    rule,
    '',
    cleanup.trimEnd(),
    '',
    `SELECT pg_temp.pd_run('${LOAD}');`,
    '',
  ].join('\n');
}

async function main() {
  const args = process.argv.slice(2);
  const flag = (name) => args.includes(name);
  const outAt = args.indexOf('--out');
  const out = outAt >= 0 ? args[outAt + 1] : null;
  if (outAt >= 0 && !out) throw new Error('--out needs a file.');
  const rehearse = flag('--rehearse');

  if (flag('--check')) {
    const [built, stored] = await Promise.all([buildSql(), readFile(MIGRATION, 'utf8').catch(() => null)]);
    if (stored !== built) {
      console.error(`${path.relative(process.cwd(), MIGRATION)} is not what the three files build. Run: node scripts/build-duplicates-sql.mjs`);
      process.exitCode = 1;
      return;
    }
    console.log('The migration is what the three files build.');
    return;
  }
  if (rehearse && !out) throw new Error('A rehearsal is written to a file: --rehearse --out rehearsal.sql');
  const sql = await buildSql({ rehearse, everything: flag('--all') });
  const target = out ?? MIGRATION;
  await writeFile(target, sql);
  console.log(`Wrote ${path.relative(process.cwd(), target)} (${sql.length.toLocaleString('en-US')} characters).`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  await main();
}
