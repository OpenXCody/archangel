// Turns the makes of the skills (data/skills/makes.json) into one idempotent
// SQL migration.
//
//   node scripts/build-makes-sql.mjs [makes.json] [catalogue.json] [output.sql]
//   node scripts/build-makes-sql.mjs --check [makes.json] [catalogue.json]
//
// A make is the named equipment or software a skill is run on: "CNC Control
// Operation" has Fanuc, Haas and Siemens; "PLC Programming" has Studio 5000
// and TIA Portal. It is a leaf beyond the skill and never replaces it. The
// file lists, for each skill that has them, its makes in the order they are
// shown. It says what makes exist for a skill, never what a company runs.
//
// --check validates the file and writes nothing. It fails unless:
//   - every entry names a skill of the catalogue (data/skills/catalogue.json),
//     exactly, and no skill is listed twice;
//   - every entry has 1 to 12 makes, each a name of 1 to 60 characters on one
//     line with no space at either end;
//   - no skill has the same make twice, in any letter case.
//
// The migration:
//   - creates skill_makes (a skill's makes) and user_skill_makes (the makes a
//     person marked, tied to their holding of the skill: taking the skill off
//     their list takes its makes with it);
//   - stops before it loads anything when the file names a skill that is not
//     stored (the catalogue's migration comes first and stores every one);
//   - loads the file's makes by skill name. A make already stored under the
//     same name in any letter case keeps its id, and so the marks people put
//     on it, and takes the file's spelling and place. A make the file does not
//     list (one an admin added) stays, after the file's.
// It never deletes a make: one the file drops is removed in Admin Tools, which
// says how many people marked it. Every step is a no-op once it has been done.
import { readFile, writeFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';

const args = process.argv.slice(2);
const checkOnly = args.includes('--check');
const [input = 'data/skills/makes.json', catalogueFile = 'data/skills/catalogue.json', output = 'migrations/0050_skill_makes.sql'] = args.filter((arg) => arg !== '--check');

export const MAKES_MAX = 12;
export const MAKE_NAME_MAX = 60;

/** Everything wrong with a makes file, as sentences. None means it can be loaded. */
export function makesProblems(makes, catalogue) {
  const problems = [];
  const entries = Array.isArray(makes?.skills) ? makes.skills : null;
  if (!entries) return ['"skills" must be a list of { skill, makes }'];
  if (entries.length === 0) problems.push('"skills" is empty');
  const known = new Set((catalogue?.skills ?? []).map((skill) => skill.name));
  const listed = new Set();
  for (const entry of entries) {
    const skill = entry?.skill;
    if (typeof skill !== 'string' || !skill) {
      problems.push('an entry has no "skill"');
      continue;
    }
    const where = `"${skill}"`;
    if (!known.has(skill)) problems.push(`${where} is not a skill in the catalogue`);
    if (listed.has(skill)) problems.push(`${where} is listed twice`);
    listed.add(skill);
    const names = Array.isArray(entry.makes) ? entry.makes : [];
    if (names.length < 1 || names.length > MAKES_MAX) problems.push(`${where} has ${names.length} makes: a skill that is listed has 1 to ${MAKES_MAX}`);
    const seen = new Set();
    for (const name of names) {
      if (typeof name !== 'string' || !name || name !== name.trim() || /[\n\r\t]/.test(name) || / {2}/.test(name) || name.length > MAKE_NAME_MAX) {
        problems.push(`${where} has a make that is not a name of 1 to ${MAKE_NAME_MAX} characters on one line: ${JSON.stringify(name)}`);
        continue;
      }
      if (seen.has(name.toLowerCase())) problems.push(`${where} lists "${name}" twice`);
      seen.add(name.toLowerCase());
    }
  }
  return problems;
}

const q = (value) => `'${String(value).replace(/'/g, "''")}'`;

/** The migration's text. `source` is the file's name, for the header. */
export function makesSql(makes, source) {
  const rows = [];
  for (const entry of makes.skills) entry.makes.forEach((name, i) => rows.push(`  (${q(entry.skill)}, ${q(name)}, ${i + 1})`));
  return [
    `-- The makes of the skills, generated from ${source} by scripts/build-makes-sql.mjs.`,
    '-- Edit the JSON and regenerate; do not edit this file by hand.',
    '-- Idempotent: each step does nothing once its rows are already as it leaves them.',
    '--',
    '-- A make is the named equipment or software a skill is run on. It is a leaf beyond',
    '-- the skill: the standard skill stays what a career names, and a person who holds',
    '-- the skill can say which of its makes they have run.',
    '',
    '-- Tables ------------------------------------------------------------------------',
    '',
    "-- A skill's makes, in the order they are shown. One name per skill, in any letter case.",
    'CREATE TABLE IF NOT EXISTS skill_makes (',
    '  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),',
    '  skill_id uuid NOT NULL REFERENCES skills (id) ON DELETE CASCADE,',
    '  name text NOT NULL,',
    '  position integer NOT NULL,',
    '  created_at timestamp DEFAULT now() NOT NULL,',
    "  -- So a person's mark can name the skill with the make (below).",
    '  CONSTRAINT skill_makes_skill_make_key UNIQUE (skill_id, id)',
    ');',
    'CREATE UNIQUE INDEX IF NOT EXISTS skill_makes_name_idx ON skill_makes (skill_id, lower(name));',
    '',
    '-- The makes a person marked. The two foreign keys hold what the rows mean: a mark',
    "-- exists only while the skill is on the person's list (taking the skill off takes",
    '-- its makes with it), and only for a make of that skill.',
    'CREATE TABLE IF NOT EXISTS user_skill_makes (',
    '  user_id uuid NOT NULL,',
    '  skill_id uuid NOT NULL,',
    '  make_id uuid NOT NULL,',
    '  created_at timestamp DEFAULT now() NOT NULL,',
    '  PRIMARY KEY (user_id, make_id),',
    '  CONSTRAINT user_skill_makes_holding_fkey FOREIGN KEY (user_id, skill_id) REFERENCES user_skills (user_id, skill_id) ON DELETE CASCADE,',
    '  CONSTRAINT user_skill_makes_make_fkey FOREIGN KEY (skill_id, make_id) REFERENCES skill_makes (skill_id, id) ON DELETE CASCADE',
    ');',
    'CREATE INDEX IF NOT EXISTS user_skill_makes_holding_idx ON user_skill_makes (user_id, skill_id);',
    'CREATE INDEX IF NOT EXISTS user_skill_makes_make_idx ON user_skill_makes (skill_id, make_id);',
    '',
    '-- The file, as rows ---------------------------------------------------------------',
    '',
    'DROP TABLE IF EXISTS pg_temp.makes_file;',
    'CREATE TEMP TABLE makes_file (skill text NOT NULL, name text NOT NULL, position integer NOT NULL, PRIMARY KEY (skill, position));',
    '',
    'INSERT INTO makes_file (skill, name, position) VALUES',
    `${rows.join(',\n')};`,
    '',
    '-- Every skill the file names must be stored ----------------------------------------',
    "-- Checked before a make is loaded. The catalogue's migration, which comes first,",
    '-- stores every skill of the catalogue, so this stops only a database that has',
    '-- gone its own way.',
    '',
    `DO $check$
DECLARE
  missing_count integer;
  missing_names text;
BEGIN
  SELECT COUNT(*), string_agg(skill, ', ' ORDER BY skill) FILTER (WHERE n <= 10) INTO missing_count, missing_names
    FROM (SELECT f.skill, ROW_NUMBER() OVER (ORDER BY f.skill) AS n FROM (SELECT DISTINCT skill FROM makes_file) f
          WHERE NOT EXISTS (SELECT 1 FROM skills s WHERE s.name = f.skill)) missing;
  IF missing_count > 0 THEN
    RAISE EXCEPTION 'skill makes: % of the skills the file names are not stored (%). No make was loaded.', missing_count, missing_names;
  END IF;
END $check$;`,
    '',
    '-- The makes ------------------------------------------------------------------------',
    '',
    "-- A make already stored takes the file's spelling and place, and keeps its id.",
    'UPDATE skill_makes m SET name = f.name, position = f.position',
    '  FROM makes_file f INNER JOIN skills s ON s.name = f.skill',
    '  WHERE m.skill_id = s.id AND lower(m.name) = lower(f.name)',
    '    AND (m.name, m.position) IS DISTINCT FROM (f.name, f.position);',
    'INSERT INTO skill_makes (skill_id, name, position)',
    '  SELECT s.id, f.name, f.position FROM makes_file f INNER JOIN skills s ON s.name = f.skill',
    '  WHERE NOT EXISTS (SELECT 1 FROM skill_makes m WHERE m.skill_id = s.id AND lower(m.name) = lower(f.name));',
    '',
    "-- A make the file does not list stays, after the file's.",
    'UPDATE skill_makes m SET position = placed.position FROM (',
    '  SELECT m.id, (SELECT COUNT(*) FROM makes_file f WHERE f.skill = s.name)',
    '           + ROW_NUMBER() OVER (PARTITION BY m.skill_id ORDER BY m.position, lower(m.name)) AS position',
    '  FROM skill_makes m INNER JOIN skills s ON s.id = m.skill_id',
    '  WHERE EXISTS (SELECT 1 FROM makes_file f WHERE f.skill = s.name)',
    '    AND NOT EXISTS (SELECT 1 FROM makes_file f WHERE f.skill = s.name AND lower(f.name) = lower(m.name))',
    ') placed WHERE placed.id = m.id AND m.position IS DISTINCT FROM placed.position;',
    '',
    'DROP TABLE pg_temp.makes_file;',
    '',
  ].join('\n');
}

async function main() {
  const makes = JSON.parse(await readFile(input, 'utf8'));
  const catalogue = JSON.parse(await readFile(catalogueFile, 'utf8'));
  const problems = makesProblems(makes, catalogue);
  if (problems.length > 0) {
    console.error(problems.join('\n'));
    console.error(`${input}: ${problems.length} problem${problems.length === 1 ? '' : 's'}.`);
    process.exit(1);
  }
  const count = makes.skills.reduce((sum, entry) => sum + entry.makes.length, 0);
  const summary = `${count} makes on ${makes.skills.length} skills`;
  if (checkOnly) {
    console.log(`${input}: valid. ${summary}.`);
    return;
  }
  const sql = makesSql(makes, input);
  await writeFile(output, sql);
  console.log(`${output}: ${sql.split('\n').length} lines. ${summary}.`);
}

// Run only when started as a script: the unit checks import the two functions.
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  await main();
}
