// Turns data/companies/domains.json into one idempotent SQL migration that
// gives each listed company its web domain (for its logo).
//
//   node scripts/build-domains-sql.mjs data/companies/domains.json migrations/0037_company_domains.sql
//
// It sets `domain` only where it is empty, on the company with exactly that
// name, and changes nothing else: no company is created, no domain that is
// already set (by an earlier migration or by an admin) is replaced, and a
// name the database does not have is passed over. Run twice, the second run
// changes no row.
import { readFile, writeFile } from 'node:fs/promises';

const [input, output] = process.argv.slice(2);
if (!input || !output) {
  console.error('usage: node scripts/build-domains-sql.mjs <input.json> <output.sql>');
  process.exit(1);
}
const q = (text) => `'${String(text).replace(/'/g, "''")}'`;
const { companies } = JSON.parse(await readFile(input, 'utf8'));
const seen = new Set();
for (const c of companies) {
  if (typeof c.name !== 'string' || c.name.trim() === '') throw new Error('a company has no name');
  if (seen.has(c.name)) throw new Error(`"${c.name}" is listed twice`);
  seen.add(c.name);
  // What the app stores: lower case, no scheme, no "www.", no path.
  if (!/^(?!www\.)[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)+$/.test(c.domain ?? '')) {
    throw new Error(`"${c.name}": "${c.domain}" is not a bare domain such as example.com`);
  }
}
const lines = [
  `-- Web domains for the companies people meet first, loaded from ${input}.`,
  '-- Generated by scripts/build-domains-sql.mjs. Edit the JSON and regenerate.',
  '-- Idempotent. Matches by exact name, creates nothing, and sets a domain only where there is none.',
  '',
  'UPDATE companies c',
  'SET domain = v.domain',
  'FROM (VALUES',
  companies.map((c) => `  (${q(c.name)}, ${q(c.domain)})`).join(',\n'),
  ') AS v(name, domain)',
  "WHERE c.name = v.name AND (c.domain IS NULL OR btrim(c.domain) = '');",
  '',
];
await writeFile(output, lines.join('\n'));
console.log(`${output}: ${companies.length} companies`);
