// Turns the curated industry sentences (data/industries/industries.json) and
// one year of official statistics (data/industries/qcew-<year>.json, written
// by scripts/ingest/qcew.mjs) into one idempotent SQL migration that fills
// industry_profiles and industry_stats.
//
//   node scripts/build-industry-stats-sql.mjs <industries.json> <qcew.json> <output.sql>
//
// Running the migration again changes nothing; a row that is already there is
// brought up to what the files say. Nothing is deleted: another year's
// figures are a new JSON file and a new generated migration, and the year
// before stays in the table.
import { readFile, writeFile } from 'node:fs/promises';

const [profilesFile, statsFile, output] = process.argv.slice(2);
if (!profilesFile || !statsFile || !output) {
  console.error('usage: node scripts/build-industry-stats-sql.mjs <industries.json> <qcew.json> <output.sql>');
  process.exit(1);
}
const q = (text) => `'${String(text).replace(/'/g, "''")}'`;
const n = (value) => (value === null || value === undefined ? 'NULL' : String(Math.round(Number(value))));

const { industries } = JSON.parse(await readFile(profilesFile, 'utf8'));
const { source, rows } = JSON.parse(await readFile(statsFile, 'utf8'));

const codes = new Set(['31-33', ...industries.map((industry) => industry.code)]);
for (const industry of industries) {
  if (!/^3[1-3]\d$/.test(industry.code) || !industry.name || !industry.summary) throw new Error(`Incomplete industry: ${JSON.stringify(industry)}`);
}
for (const row of rows) {
  if (!codes.has(row.code)) throw new Error(`Statistics for an industry that is not listed: ${row.code}`);
  if (!/^(US|[A-Z]{2})$/.test(row.state)) throw new Error(`Not a state: ${row.state}`);
}
if (!Number.isInteger(source?.year)) throw new Error('The statistics file names no year');

const sourceName = `${source.publisher}, ${source.name}`;
const profileRows = industries.map((industry) => `  (${q(industry.code)}, ${q(industry.name)}, ${q(industry.summary)})`);
const statRows = rows.map(
  (row) => `  (${q(row.state)}, ${q(row.code)}, ${n(row.establishments)}, ${n(row.employment)}, ${n(row.avgAnnualPay)})`
);

const lines = [
  `-- What each industry makes (${profilesFile}) and the official figures for ${source.year}`,
  `-- (${statsFile}: ${sourceName}, retrieved ${source.retrieved}).`,
  '-- Generated by scripts/build-industry-stats-sql.mjs. Edit the JSON and regenerate; once this',
  '-- file has been applied anywhere, a change goes out as a new migration instead.',
  '-- Idempotent: rows are matched by key and brought up to date; nothing is deleted.',
  '',
  'INSERT INTO "industry_profiles" ("code", "name", "summary") VALUES',
  profileRows.join(',\n'),
  'ON CONFLICT ("code") DO UPDATE SET "name" = EXCLUDED."name", "summary" = EXCLUDED."summary";',
  '',
  'INSERT INTO "industry_stats" ("state", "industry_code", "year", "establishments", "employment", "avg_annual_pay", "source", "source_url")',
  `SELECT v.state, v.industry_code, ${source.year}, v.establishments::integer, v.employment::integer, v.avg_annual_pay::integer, ${q(sourceName)}, ${q(source.url)}`,
  'FROM (VALUES',
  statRows.join(',\n'),
  ') AS v(state, industry_code, establishments, employment, avg_annual_pay)',
  'ON CONFLICT ("state", "industry_code", "year") DO UPDATE SET',
  '  "establishments" = EXCLUDED."establishments", "employment" = EXCLUDED."employment",',
  '  "avg_annual_pay" = EXCLUDED."avg_annual_pay", "source" = EXCLUDED."source", "source_url" = EXCLUDED."source_url";',
  '',
];
await writeFile(output, lines.join('\n'));
console.log(`${output}: ${profileRows.length} industries, ${statRows.length} rows of ${source.year} statistics`);
