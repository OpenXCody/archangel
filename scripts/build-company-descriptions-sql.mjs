// Turns the `industry` and `description` of each company in
// data/companies/profiles.json into one idempotent SQL migration.
//
//   node scripts/build-company-descriptions-sql.mjs <input.json> <output.sql>
//
// It matches companies by exact name and creates none. A description that is
// already set is kept, and so is an industry unless it is empty or the generic
// "Manufacturing" the bulk import stamped on nearly every company: a correction
// made by hand survives a re-run.
import { readFile, writeFile } from 'node:fs/promises';

const [input, output] = process.argv.slice(2);
if (!input || !output) {
  console.error('usage: node scripts/build-company-descriptions-sql.mjs <input.json> <output.sql>');
  process.exit(1);
}
const q = (text) => `'${String(text).replace(/'/g, "''")}'`;
const { companies } = JSON.parse(await readFile(input, 'utf8'));
const described = companies.filter((c) => c.description && c.industry);
const lines = [
  `-- Company industries and one-line descriptions loaded from ${input}.`,
  '-- Generated by scripts/build-company-descriptions-sql.mjs. Edit the JSON and regenerate.',
  '-- Idempotent. Matches by exact name, creates nothing, keeps what is already set',
  "-- (except the generic industry 'Manufacturing').",
  '',
  'UPDATE companies c',
  "SET description = COALESCE(NULLIF(btrim(c.description), ''), v.description),",
  '    industry = CASE',
  "      WHEN c.industry IS NULL OR btrim(c.industry) = '' OR lower(btrim(c.industry)) = 'manufacturing' THEN v.industry",
  '      ELSE c.industry',
  '    END',
  'FROM (VALUES',
  described.map((c) => `  (${q(c.name)}, ${q(c.industry)}, ${q(c.description)})`).join(',\n'),
  ') AS v(name, industry, description)',
  'WHERE c.name = v.name;',
  '',
];
await writeFile(output, lines.join('\n'));
console.log(`${output}: ${described.length} companies`);
