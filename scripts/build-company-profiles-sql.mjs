// Turns data/companies/profiles.json into one idempotent SQL migration that
// sets each listed company's web domain (for its logo) and featured flag.
//
//   node scripts/build-company-profiles-sql.mjs <input.json> <output.sql>
//
// It matches companies by exact name, creates none, and never overwrites a
// domain that is already set, so a correction made by hand survives a re-run.
import { readFile, writeFile } from 'node:fs/promises';

const [input, output] = process.argv.slice(2);
if (!input || !output) {
  console.error('usage: node scripts/build-company-profiles-sql.mjs <input.json> <output.sql>');
  process.exit(1);
}
const q = (text) => `'${String(text).replace(/'/g, "''")}'`;
const { companies } = JSON.parse(await readFile(input, 'utf8'));
const seen = new Set();
for (const c of companies) {
  if (seen.has(c.name)) throw new Error(`"${c.name}" is listed twice`);
  seen.add(c.name);
}
const lines = [
  `-- Company domains and featured flags loaded from ${input}.`,
  '-- Generated by scripts/build-company-profiles-sql.mjs. Edit the JSON and regenerate.',
  '-- Idempotent. Matches by exact name, creates nothing, keeps a domain that is already set.',
  '',
  'UPDATE companies c',
  'SET domain = COALESCE(c.domain, v.domain),',
  '    featured = c.featured OR v.featured',
  'FROM (VALUES',
  companies.map((c) => `  (${q(c.name)}, ${q(c.domain)}, ${c.featured ? 'true' : 'false'})`).join(',\n'),
  ') AS v(name, domain, featured)',
  'WHERE c.name = v.name;',
  '',
];
await writeFile(output, lines.join('\n'));
console.log(`${output}: ${companies.length} companies`);
